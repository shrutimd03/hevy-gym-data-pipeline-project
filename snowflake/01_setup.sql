USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS HEVY_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND   = 60
  AUTO_RESUME    = TRUE
  INITIALLY_SUSPENDED = TRUE;

-- db + schemas.
CREATE DATABASE IF NOT EXISTS HEVY;
CREATE SCHEMA IF NOT EXISTS HEVY.BRONZE;
CREATE SCHEMA IF NOT EXISTS HEVY.RAW; 
CREATE SCHEMA IF NOT EXISTS HEVY.STAGING;  
CREATE SCHEMA IF NOT EXISTS HEVY.MARTS;   
CREATE SCHEMA IF NOT EXISTS HEVY.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS HEVY.AI;

CREATE ROLE IF NOT EXISTS DBT_ROLE;
GRANT USAGE ON WAREHOUSE HEVY_WH TO ROLE DBT_ROLE;
GRANT OPERATE ON WAREHOUSE HEVY_WH TO ROLE DBT_ROLE;
GRANT ALL ON ALL SCHEMAS IN DATABASE HEVY TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE SCHEMAS IN DATABASE HEVY TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE TABLES IN DATABASE HEVY TO ROLE DBT_ROLE;
GRANT ALL ON FUTURE VIEWS IN DATABASE HEVY TO ROLE DBT_ROLE;

SET my_user = CURRENT_USER();
GRANT ROLE DBT_ROLE TO USER IDENTIFIER($my_user);

SELECT 'setup complete' AS status;
