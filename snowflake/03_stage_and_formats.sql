USE ROLE ACCOUNTADMIN;
USE DATABASE HEVY;
USE SCHEMA RAW;

CREATE OR REPLACE FILE FORMAT HEVY.RAW.CSV_FILE_FORMAT
  TYPE = 'CSV'
  COMPRESSION = 'AUTO'                   
  FIELD_DELIMITER = ','
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  SKIP_HEADER = 1                          
  EMPTY_FIELD_AS_NULL = TRUE
  NULL_IF = ('', '\\N', 'NULL')
  TRIM_SPACE = FALSE
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE OR REPLACE FILE FORMAT HEVY.RAW.JSON_FORMAT
    TYPE = JSON
    STRIP_OUTER_ARRAY = TRUE;
    
CREATE OR REPLACE STAGE HEVY.RAW.HEVY_RAW_STG_CSV
  STORAGE_INTEGRATION = HEVY_S3_INT
  URL = 's3://hevy-gym-pipeline/raw/csv/'
  FILE_FORMAT = HEVY.RAW.CSV_FILE_FORMAT;

CREATE OR REPLACE STAGE HEVY.RAW.HEVY_RAW_STG_JSON
  STORAGE_INTEGRATION = HEVY_S3_INT
  URL = 's3://hevy-gym-pipeline/raw/json/'
  FILE_FORMAT = HEVY.RAW.JSON_FILE_FORMAT;


LIST @HEVY.RAW.HEVY_RAW_STG_CSV;
LIST @HEVY.RAW.HEVY_RAW_STG_JSON;
