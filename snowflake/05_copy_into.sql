USE ROLE ACCOUNTADMIN;
USE DATABASE HEVY;
USE SCHEMA RAW;
USE WAREHOUSE HEVY_WH;

COPY INTO RAW.USER_INFO
FROM @HEVY_RAW_STG_CSV/user_info
ON_ERROR = 'CONTINUE';

select * from USER_INFO;

COPY INTO RAW.USER_GOALS
FROM @HEVY_RAW_STG_CSV/user_goals
ON_ERROR = 'CONTINUE';

select * from USER_GOALS;

COPY INTO RAW.MEASUREMENT_DATA
FROM @HEVY_RAW_STG_CSV/measurement_data
ON_ERROR = 'CONTINUE';

select * from MEASUREMENT_DATA;

COPY INTO RAW.WORKOUT_SESSION
FROM @HEVY_RAW_STG_CSV/workout_session
ON_ERROR = 'CONTINUE';

select * from WORKOUT_SESSION;

COPY INTO RAW.WORKOUT_DATA
FROM @HEVY_RAW_STG_CSV/workout_data
ON_ERROR = 'CONTINUE';

select * from WORKOUT_DATA;

COPY INTO RAW.WORKOUT_ROUTINES
FROM @HEVY_RAW_STG_CSV/workout_routines
ON_ERROR = 'CONTINUE';

select * from WORKOUT_ROUTINES;

COPY INTO RAW.ROUTINE_EXERCISES
FROM @HEVY_RAW_STG_CSV/routine_exercises
ON_ERROR = 'CONTINUE';

select * from ROUTINE_EXERCISES;


COPY INTO HEVY.RAW.EXERCISES (RAW_DATA)
FROM @HEVY.RAW.HEVY_RAW_STG_JSON/exercises/
FILES = ('exercises.json')
FILE_FORMAT = (FORMAT_NAME = HEVY.RAW.JSON_FORMAT)
FORCE = TRUE
ON_ERROR = 'CONTINUE';

select * from EXERCISES;
